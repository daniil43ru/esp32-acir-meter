#!/usr/bin/env python3
"""
Численная проверка измерительной математики ACIR-метра (v2).

Считает, что прибор показал бы в идеальных и реальных условиях:
  - ток возбуждения (по ПЕРВОЙ ГАРМОНИКЕ меандра),
  - напряжение на Ri,
  - уровень сигнала на выходе LM358,
  - сколько отсчётов АЦП,
  - погрешность от смещения усилителя,
  - что даёт калибровка по эталонному резистору.

ВАЖНО (исправление M6): смещение LM358 НЕ нужно складывать с сигналом
напрямую. Оба они складываются на ВЫХОДЕ усилителя в вольтах, после
усиления. Прошлая версия складывала до деления на GAIN — это завышало
эффект смещения в 48 раз.

Запуск:  python model_check.py
"""

import math

# ── Параметры тракта (совпадают со схемой и прошивкой) ─────────────────────
VREF       = 3.3
GAIN       = 48.0
R_FORCE    = 100.0
R_SHUNT    = 1.0
R_GPIO     = 20.0        # выходное сопротивление пина ESP32
C_DC       = 10e-6
F_EXC      = 1000.0
V_EXC_PEAK = 1.65        # половина размаха меандра 0..3.3
V_DIV      = 2.0
ADC_BITS   = 12
ADC_MAX    = (1 << ADC_BITS) - 1
N_LOCKIN   = 2000


def excitation_current():
    """Пиковый ток ПЕРВОЙ ГАРМОНИКИ в элементе, А.

    LEDC даёт меандр 0..3.3 В. Первая гармоника меандра = (4/π)·(V_pp/2).
    Lock-in выделяет именно её, поэтому считать надо по ней.
    """
    zc = 1.0 / (2 * math.pi * F_EXC * C_DC)
    r = R_FORCE + R_SHUNT + R_GPIO
    v_fund_peak = V_EXC_PEAK * (4.0 / math.pi)
    return v_fund_peak / math.sqrt(r * r + zc * zc)


def measure(ri_ohm, offset_mv=0.0):
    """Что увидит прибор при внутреннем сопротивлении ri_ohm (Ом).

    offset_mv — постоянное смещение LM358 на ВЫХОДЕ, мВ (это уже усиленное
    смещение, приведённое к выходу). Возвращает (истинное Ri, показанное v1,
    показанное v2) в мОм.
    """
    i_pk = excitation_current()
    u_sense_pk = i_pk * ri_ohm                       # В на клемме
    u_out_true = u_sense_pk * GAIN                   # В на выходе LM358
    u_out_err  = (offset_mv / 1000.0)                # В, добавка смещения

    # v1 брала min/max огибающей. Постоянное смещение на выходе НЕ влияет
    # на разность max-min — поэтому смещение само по себе не ломало v1.
    v1_measured = u_out_true / GAIN / i_pk * 1000.0

    # v2 вычитает векторно замеренный офсет — тоже не зависит от постоянки.
    v2_measured = u_out_true / GAIN / i_pk * 1000.0

    return ri_ohm * 1000.0, v1_measured, v2_measured, u_out_true, u_out_err


def adc_counts(u_out_pk):
    """Сколько отсчётов АЦП даст пиковое напряжение на выходе."""
    return u_out_pk / VREF * ADC_MAX


def main():
    i_pk = excitation_current()
    print("=" * 74)
    print(" ACIR METER — численная модель (после исправлений)")
    print("=" * 74)
    print(f"ток возбуждения (1-я гармоника, пик): {i_pk * 1000:8.2f} мА")
    print(f"усиление LM358:                       {GAIN:8.1f}")
    print(f"АЦП:                                  {ADC_BITS:8d} бит ({ADC_MAX})")
    print(f"lock-in выигрыш по амплитуде шума:     {math.sqrt(N_LOCKIN):8.1f}x")
    print()

    print("─" * 74)
    print(" Таблица 1: ожидаемые значения для разных Ri")
    print("─" * 74)
    print(f"{'Ri, мОм':>9} | {'U на клемме':>13} | {'U на выходе':>13} | "
          f"{'отсчётов АЦП':>13} | {'% рейла':>8}")
    print("-" * 74)
    for ri_mohm in [10, 20, 30, 50, 80, 100, 200, 500]:
        ri = ri_mohm / 1000.0
        u_sense = i_pk * ri
        u_out = u_sense * GAIN
        counts = adc_counts(u_out)
        pct = u_out / 1.65 * 100      # доступный размах до рейла 1.65 В
        print(f"{ri_mohm:9d} | {u_sense*1000:9.3f} мВ | {u_out*1000:9.2f} мВ | "
              f"{counts:13.1f} | {pct:7.1f} %")
    print()
    print("Рейл LM358 при смещении 1.65 В: доступно ~1.65 В пик до 3.3 В.")
    print("Все рабочие значения Ri (до 200 мОм) далеко от насыщения.")
    print()

    print("─" * 74)
    print(" Таблица 2: ошибка от смещения LM358")
    print("─" * 74)
    print("LM358: типовое смещение 2 мВ, максимальное 7 мВ на ВХОДЕ.")
    print("На выходе оно усиливается в GAIN раз: 2 мВ -> 96 мВ, 7 мВ -> 336 мВ.")
    print()
    print("КЛЮЧЕВОЕ: постоянное смещение на выходе НЕ влияет ни на min/max,")
    print("ни на lock-in — оба считают переменную составляющую. Ломает их")
    print("только ШУМ (пики) и упирание сигнала в рейл АЦП.")
    print()
    print(f"{'Ri, мОм':>9} | {'смещ. вх':>9} | {'смещ. вых':>11} | "
          f"{'запас до 1.65 В':>17}")
    print("-" * 74)
    for ri_mohm in [20, 50, 100, 200]:
        for off_in_mv in [2.0, 7.0]:
            # смещение задано на ВХОДЕ усилителя -> на выходе умножается на GAIN
            off_out_mv = off_in_mv * GAIN
            true, v1, v2, u_out, u_err = measure(ri_mohm / 1000.0, off_out_mv)
            headroom = 1.65 - u_err - u_out
            print(f"{ri_mohm:9d} | {off_in_mv:7.1f} мВ | {u_err*1000:9.1f} мВ | "
                  f"{headroom*1000:15.1f} мВ")
    print()
    print("Вывод: при Ri до 200 мОм и смещении до 7 мВ запас есть даже")
    print("с учётом 50 %-ной перегрузки по пику шума.")
    print()

    print("─" * 74)
    print(" Таблица 3: разрешение по АЦП")
    print("─" * 74)
    u_lsb = VREF / ADC_MAX / GAIN
    ri_lsb = u_lsb / i_pk * 1000.0
    print(f"1 отсчёт АЦП              = {VREF/ADC_MAX*1000:.3f} мВ")
    print(f"на клемме (÷{GAIN:.0f})         = {u_lsb*1e6:.2f} мкВ")
    print(f"соответствует Ri          = {ri_lsb:.3f} мОм")
    print()
    print("Вывод: разрешение ~1 мОм — более чем достаточно. Реальный")
    print("предел ставит шум LM358, а не АЦП. Поэтому lock-in важен.")
    print()

    print("─" * 74)
    print(" Таблица 4: что даёт калибровка по эталонному резистору")
    print("─" * 74)
    print("Пусть Rforce на самом деле 105 Ом (+5 %), а прошивка считает 100.")
    zc = 1 / (2 * math.pi * F_EXC * C_DC)
    i_real = V_EXC_PEAK * (4/math.pi) / math.sqrt((105.0 + R_SHUNT + R_GPIO)**2 + zc**2)
    i_assumed = excitation_current()
    ratio = i_assumed / i_real
    print(f"  ток реальный:      {i_real*1000:8.3f} мА")
    print(f"  ток по номиналам:  {i_assumed*1000:8.3f} мА")
    print(f"  ошибка Ri без калибровки: {ratio*100-100:+.1f} %")
    print(f"  K_CAL, который это исправит: {ratio:.4f}")
    print()
    print("Калибровка по резистору 50 мОм подбирает K_CAL так, чтобы")
    print("показание совпало с номиналом — и убирает этот разброс.")
    print()
    print("=" * 74)


if __name__ == "__main__":
    main()
