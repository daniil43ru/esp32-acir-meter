#!/usr/bin/env python3
"""
Проверка времени установления усилителя LM358 (Rg × Crg).

Усилитель неинвертирующий: по переменке K = 1 + Rf/Zg, где
Zg = Rg + 1/(j·ω·Crg). На 1 кГц Crg даёт всего −j15.9 Ом — реактивная
составляющая мала, поэтому |K| ≈ 48, а фаза ≈ 0.9°.

Но переходный процесс при включении возбуждения идёт с постоянной
времени tau = (Rg ∥ Rf) · Crg ≈ Rg·Crg = 10 мс. Это и есть проблема:
замер, начатый раньше, занижает усиление, а значит и Ri.

Запуск:  python test_settling.py
"""

import math

RF = 47000.0
RG = 1000.0
CRG = 10e-6
F = 1000.0
GAIN_DC = RF / RG          # прирост усиления сверх 1
GAIN_AC = 1.0 + GAIN_DC

TAU = RG * CRG             # 10 мс (доминирует Rg, т.к. Rf >> Rg)


def gain_at(t):
    """Эффективное усиление через t секунд после включения."""
    return 1.0 + GAIN_DC * (1.0 - math.exp(-t / TAU))


def avg_gain_over_window(t_start, n, step_us):
    acc = 0.0
    for i in range(n):
        acc += gain_at(t_start + i * step_us * 1e-6)
    return acc / n


def main():
    print("=" * 72)
    print(" Установление усилителя: влияние на измерение")
    print("=" * 72)
    print(f"Rf={RF:.0f} Rg={RG:.0f} Crg={CRG*1e6:.0f} мкФ -> tau = {TAU*1000:.1f} мс")
    print(f"установившееся усиление = {GAIN_AC:.2f}")
    print()

    print("─" * 72)
    print(" Мгновенное усиление после включения возбуждения")
    print("─" * 72)
    print(f"{'t, мс':>8} | {'усиление':>10} | {'от 48':>8} | {'Ri покажет':>11}")
    print("-" * 72)
    for t_ms in [0, 1, 2, 5, 10, 20, 30, 40, 50]:
        g = gain_at(t_ms / 1000.0)
        dev = (g - GAIN_AC) / GAIN_AC * 100
        # если замер сделан ровно в этот момент — во сколько раз ошибётся Ri
        ri_err = (GAIN_AC / g - 1) * 100
        print(f"{t_ms:8.0f} | {g:10.2f} | {dev:+7.1f} % | {ri_err:+9.1f} %")
    print()

    print("─" * 72)
    print(" Среднее усиление за окно замера (N=2000, шаг 25 мкс = 50 мс)")
    print("─" * 72)
    print(f"{'задержка':>9} | {'ср. усиление':>13} | {'ошибка Ri':>11}")
    print("-" * 72)
    for delay_ms in [0, 2, 5, 10, 20, 30, 50]:
        avg = avg_gain_over_window(delay_ms / 1000.0, 2000, 25)
        err = (GAIN_AC / avg - 1) * 100
        print(f"{delay_ms:7.0f} мс | {avg:13.2f} | {err:+9.1f} %")
    print()

    print("─" * 72)
    print(" Вывод")
    print("─" * 72)
    print("При delay(2) замер идёт с начала окна, где усиление ещё ~9, а не 48.")
    print("Среднее за окно выходит ~40 вместо 48 -> сигнал занижен,")
    print("а значит Ri ЗАВЫШАЕТСЯ на ~19 %.")
    print()
    print("Исправление: SETTLE_ON_MS = 50 (5·tau). После этого среднее усиление")
    print(f"за окно ~{avg_gain_over_window(0.050, 2000, 25):.2f} — ошибка < 1 %.")
    print()
    print("Альтернатива, если важна скорость: уменьшить Crg до 1 мкФ")
    print(f"(tau = {RG*1e-6*1000:.1f} мс), но тогда на 1 кГц появится заметный")
    print("фазовый сдвиг — придётся учитывать фазу при расчёте.")


if __name__ == "__main__":
    main()